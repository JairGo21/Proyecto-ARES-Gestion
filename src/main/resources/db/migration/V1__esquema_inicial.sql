-- Reglas de persistencia del curso:
--   * Solo las clases «entity» tienen tabla.
--   * Los atributos derivados (/stockActual, /diasRestantes) NO son columnas.
--   * Las enumeraciones se guardan como texto con CHECK.
--   * Las asociaciones se vuelven llaves foráneas.
--
-- IMPORTANTE: Flyway ejecuta cada archivo una sola vez. Un archivo que ya está
-- en main NO se edita: cualquier cambio va en un archivo nuevo (V3__..., V4__...).
