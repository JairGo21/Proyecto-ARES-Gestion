CREATE TABLE usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    usuario          VARCHAR(40)  NOT NULL,
    contrasena_hash  VARCHAR(100) NOT NULL,
    rol              VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_usuario_usuario UNIQUE (usuario),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMINISTRADOR', 'SUPERVISOR', 'AUXILIAR'))
);

CREATE TABLE producto (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(120) NOT NULL,
    perecedero       BOOLEAN      NOT NULL,
    cantidad_minima  INTEGER,
    dias_aviso       INTEGER      NOT NULL,
    activo           BOOLEAN      DEFAULT TRUE NOT NULL,
    CONSTRAINT uq_producto_nombre UNIQUE (nombre),
    CONSTRAINT ck_producto_minimo CHECK (cantidad_minima IS NULL OR cantidad_minima >= 0),
    CONSTRAINT ck_producto_aviso CHECK (dias_aviso >= 0)
);

CREATE TABLE lote (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id          BIGINT  NOT NULL,
    fecha_vencimiento    DATE,
    cantidad_disponible  INTEGER NOT NULL,
    priorizado           BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_lote_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT ck_lote_cantidad CHECK (cantidad_disponible >= 0)
);

CREATE TABLE alerta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id     BIGINT      NOT NULL,
    lote_id         BIGINT,
    tipo            VARCHAR(20) NOT NULL,
    estado          VARCHAR(10) NOT NULL,
    fecha_creacion  TIMESTAMP   NOT NULL,
    fecha_cierre    TIMESTAMP,
    CONSTRAINT fk_alerta_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT fk_alerta_lote FOREIGN KEY (lote_id) REFERENCES lote (id),
    CONSTRAINT ck_alerta_tipo CHECK (tipo IN ('PROXIMO_A_VENCER', 'VENCIDO', 'STOCK_MINIMO')),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('ABIERTA', 'CERRADA')),
    -- Solo las alertas de vencimiento señalan un lote.
    CONSTRAINT ck_alerta_lote CHECK (
        (tipo = 'STOCK_MINIMO' AND lote_id IS NULL) OR (tipo <> 'STOCK_MINIMO' AND lote_id IS NOT NULL)
    )
);

CREATE TABLE notificacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT       NOT NULL,
    alerta_id       BIGINT       NOT NULL,
    titulo          VARCHAR(120) NOT NULL,
    mensaje         VARCHAR(500) NOT NULL,
    fecha_creacion  TIMESTAMP    NOT NULL,
    leida           BOOLEAN      DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_notificacion_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_notificacion_alerta FOREIGN KEY (alerta_id) REFERENCES alerta (id)
);

CREATE TABLE movimiento_inventario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id     BIGINT       NOT NULL,
    usuario_id  BIGINT       NOT NULL,
    tipo        VARCHAR(20)  NOT NULL,
    cantidad    INTEGER      NOT NULL,
    fecha       TIMESTAMP    NOT NULL,
    motivo      VARCHAR(255),
    CONSTRAINT fk_movimiento_lote FOREIGN KEY (lote_id) REFERENCES lote (id),
    CONSTRAINT fk_movimiento_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN
        ('ENTRADA', 'SALIDA_VENTA', 'BAJA_VENCIMIENTO', 'BAJA_DANO', 'BAJA_OTRO', 'ANULACION')),
    CONSTRAINT ck_movimiento_cantidad CHECK (cantidad > 0)
);

CREATE TABLE sugerido_compra (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL,
    fecha       TIMESTAMP   NOT NULL,
    estado      VARCHAR(20) NOT NULL,
    CONSTRAINT fk_sugerido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_sugerido_estado CHECK (estado IN ('PENDIENTE_RECEPCION', 'RECIBIDO_PARCIAL', 'RECIBIDO'))
);

CREATE TABLE item_sugerido (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sugerido_id          BIGINT  NOT NULL,
    producto_id          BIGINT  NOT NULL,
    cantidad_sugerida    INTEGER NOT NULL,
    cantidad_confirmada  INTEGER NOT NULL,
    CONSTRAINT fk_item_sugerido FOREIGN KEY (sugerido_id) REFERENCES sugerido_compra (id),
    CONSTRAINT fk_item_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT ck_item_cantidades CHECK (cantidad_sugerida >= 0 AND cantidad_confirmada >= 0)
);

CREATE INDEX ix_lote_producto ON lote (producto_id);
CREATE INDEX ix_lote_vencimiento ON lote (fecha_vencimiento);
CREATE INDEX ix_movimiento_lote ON movimiento_inventario (lote_id);
CREATE INDEX ix_alerta_lote ON alerta (lote_id);
