-- CU-05. Rangos de temporadas altas configurables.
-- El equipo tiene una migracion V4 pendiente (PR #24).
-- Integrar V4 antes de aplicar V5 en una base persistente.
CREATE TABLE temporada_alta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    CONSTRAINT ck_temporada_fechas CHECK (fecha_fin >= fecha_inicio)
);
CREATE INDEX ix_temporada_rango ON temporada_alta(fecha_inicio, fecha_fin);
